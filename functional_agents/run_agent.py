def _print_summary(res: dict[str, Any]) -> None:
    mt = res["mini_trace"]
    d = res["diff"]
    print(f"\n=== Agent Harness — {mt['agent']} ({mt['agent_class']}) ===")
    print(f"  status         : {mt['status']}")
    if mt.get("error"):
        print(f"  error          : {mt['error']}")
    print(f"  time           : {mt['execution_time_ms']} ms")
    print(f"  llm calls      : {mt['llm_call_count']} ({mt['llm_mode']})")
    print(f"  preconditions  : {'; '.join(mt['validation']['preconditions_passed']) or '(none)'}")
    print(f"  postconditions : {'; '.join(mt['validation']['postconditions_passed']) or '(none)'}")
    for name, bd in (mt.get("boundary") or {}).items():
        stages = bd.get("stages") if isinstance(bd, dict) else None
        failed = bd.get("failed_stage") if isinstance(bd, dict) else None
        print(f"  {name:<15}: stages={stages} failed_stage={failed}")
    for name, ps in (mt.get("prompt_slice") or {}).items():
        if not isinstance(ps, dict):
            continue
        print(
            f"  {name:<15}: {ps.get('original_bytes')}→{ps.get('sliced_bytes')} bytes "
            f"({ps.get('reduction_pct')}% reduction, {ps.get('fields_excluded_count')} fields excluded)"
        )
    print("\n  Context diff:")
    print(f"    added    ({len(d['added'])}): {', '.join(d['added']) or '-'}")
    print(f"    modified ({len(d['modified'])}): {', '.join(d['modified']) or '-'}")
    print(f"    unchanged({len(d['unchanged'])})")
    if mt["warnings"]:
        print(f"\n  Warnings: {mt['warnings']}")
    print("")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m functional_agents.run_agent",
        description="Execute one Functional Agent in isolation (PH2.0).",
    )
    parser.add_argument("--agent", required=True, help=f"One of: {', '.join(sorted(AGENT_REGISTRY))}")
    parser.add_argument("--fixture", required=True, help="Path to AgentContext fixture JSON")
    parser.add_argument("--output", help="Write updated context JSON here")
    parser.add_argument("--trace", help="Write mini trace JSON here")
    parser.add_argument("--no-llm", action="store_true", help="Force deterministic mock client")
    parser.add_argument("--model", help="Anthropic model name (live mode)")
    parser.add_argument("--sources", default="fixtures/sources", help="Sources dir for evidence legacy path")
    parser.add_argument("--knowledge-store", help="Knowledge store dir (auto-detects knowledge_store/)")
    parser.add_argument("--out", default="outputs/harness_report.md", help="Report output path (report agent)")
    parser.add_argument("--log-level", default="WARNING")
    args = parser.parse_args(argv)

    logging.basicConfig(level=getattr(logging, args.log_level.upper(), logging.WARNING),
                        format="%(levelname)s %(name)s: %(message)s")

    try:
        res = run_agent(
            args.agent, args.fixture,
            no_llm=args.no_llm, model=args.model,
            sources=args.sources, knowledge_store=args.knowledge_store, out_path=args.out,
        )
    except HarnessError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    _print_summary(res)

    if args.output:
        Path(args.output).parent.mkdir(parents=True, exist_ok=True)
        Path(args.output).write_text(json.dumps(res["context"], indent=2, ensure_ascii=False), encoding="utf-8")
        print(f"Updated context → {args.output}")
    if args.trace:
        Path(args.trace).parent.mkdir(parents=True, exist_ok=True)
        Path(args.trace).write_text(json.dumps(res["mini_trace"], indent=2, ensure_ascii=False), encoding="utf-8")
        print(f"Mini trace → {args.trace}")

    # Non-zero exit on an execution/boundary failure (deterministic).
    return 0 if res["mini_trace"]["status"] != "error" else 1


if __name__ == "__main__":
    raise SystemExit(main())
