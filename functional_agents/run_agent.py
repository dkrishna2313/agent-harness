"""Agent-level execution harness (PH2.0).

Run ONE Functional Agent in isolation against a serialized AgentContext fixture,
validate pre/post-conditions, emit a context diff and a mini trace. This is an
ADDITIONAL execution path — it does not modify the Functional Agent Contract,
AgentContext/AgentResult schemas, or the Orchestrator.

Usage:
    python -m functional_agents.run_agent --agent planner --fixture fixtures/planner_start.json
    python -m functional_agents.run_agent --agent evidence --fixture fixtures/evidence_start.json --no-llm
    python -m functional_agents.run_agent --agent recommendation \
        --fixture fixtures/recommendation_start.json --output updated_context.json --trace mini.trace.json

Fixture format: a JSON object of AgentContext fields (the durable ones). Unknown
keys are ignored; missing fields fall back to AgentContext defaults. See
fixtures/README.md.
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
import time
from pathlib import Path
from typing import Any, Callable

from .context import AgentContext
from .context_snapshot import (
    HarnessError,
    CONTEXT_FIELDS,
    context_to_jsonable,
    load_context,
    context_diff,
)

LOGGER = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Precondition / postcondition specs
# ---------------------------------------------------------------------------

def _has_question_or_target(ctx: AgentContext) -> bool:
    return bool((ctx.question or "").strip()) or bool(ctx.get_reasoning_targets())


def _plan_present(ctx: AgentContext) -> bool:
    return bool(ctx.plan) and bool(ctx.plan.get("subquestions") or ctx.plan.get("investigation_areas"))


def _evidence_present(ctx: AgentContext) -> bool:
    return bool(ctx.evidence_notes) and bool(ctx.evidence_notes[0].get("evidence_items") is not None)


def _hypotheses_present(ctx: AgentContext) -> bool:
    return bool(ctx.hypotheses)


def _prepare_report(ctx: AgentContext) -> None:
    """ReportAgent needs a ResearchMemo object in trace scratch (not JSON-able).

    Rebuild it from a fixture-provided `trace._memo` dict, or synthesize a minimal
    memo from the question + evidence so the report agent can run in isolation.
    """
    from research_agent.schemas import ResearchMemo, EvidenceItem

    memo = ctx.trace.get("_memo")
    if isinstance(memo, ResearchMemo):
        pass
    elif isinstance(memo, dict):
        ctx.trace["_memo"] = ResearchMemo(**memo)
    else:
        ev_note = ctx.evidence_notes[0] if ctx.evidence_notes else {}
        facts = [e.get("claim", "") for e in ev_note.get("evidence_items", [])][:5]
        ctx.trace["_memo"] = ResearchMemo(
            title=f"Report: {ctx.question}",
            question=ctx.question or "(harness)",
            executive_summary="Synthetic memo generated by the agent harness.",
            confirmed_facts=[f for f in facts if f],
        )
    ctx.trace.setdefault("_documents", [])


# Registry: name -> builder + pre/post conditions + declared products.
# Each condition is (description, predicate(ctx)->bool).
AGENT_REGISTRY: dict[str, dict[str, Any]] = {
    "planner": {
        "import": ("planner_agent", "PlannerAgent"),
        "build": lambda cls, client, profiles, cfg: cls(client=client, domain_profiles=profiles),
        "pre": [("question or reasoning target present", _has_question_or_target)],
        "post": [("plan.research_type produced", lambda c: bool(c.plan.get("research_type")))],
        "produces": ["plan", "domain_plans"],
    },
    "evidence": {
        "import": ("evidence_agent", "EvidenceAgent"),
        "build": lambda cls, client, profiles, cfg: cls(
            sources_dir=cfg["sources"], client=client, domain_profiles=profiles,
            retriever=cfg.get("retriever"), use_reranker=cfg.get("rerank", False),
        ),
        "pre": [("plan present (subquestions/investigation_areas)", _plan_present)],
        "post": [("evidence_notes produced", lambda c: bool(c.evidence_notes))],
        "produces": ["evidence_notes", "domain_evidence"],
    },
    "hypothesis": {
        "import": ("hypothesis_agent", "HypothesisAgent"),
        "build": lambda cls, client, profiles, cfg: cls(client=client, domain_profiles=profiles),
        "pre": [("evidence_notes present", _evidence_present)],
        "post": [("hypotheses produced", lambda c: bool(c.hypotheses))],
        "produces": ["hypotheses", "domain_hypotheses"],
    },
    "strategic_synthesis": {
        "import": ("strategic_synthesis_agent", "StrategicSynthesisAgent"),
        "build": lambda cls, client, profiles, cfg: cls(client=client, domain_profiles=profiles),
        "pre": [("hypotheses or domain_hypotheses present",
                 lambda c: bool(c.hypotheses or c.domain_hypotheses))],
        "post": [("strategic_synthesis produced", lambda c: bool(c.strategic_synthesis))],
        "produces": ["strategic_synthesis"],
    },
    "recommendation": {
        "import": ("recommendation_agent", "RecommendationAgent"),
        "build": lambda cls, client, profiles, cfg: cls(client=client, domain_profiles=profiles),
        "pre": [("hypotheses present", _hypotheses_present)],
        "post": [("recommendations produced", lambda c: bool(c.recommendations))],
        "produces": ["recommendations", "recommendation_portfolio"],
    },
    "report": {
        "import": ("report_agent", "ReportAgent"),
        "build": lambda cls, client, profiles, cfg: cls(out_path=cfg["out"], domain_profile=None),
        "prepare": _prepare_report,
        "pre": [("question present", lambda c: bool((c.question or "").strip()))],
        "post": [("report artifact produced", lambda c: bool(c.artifacts.get("report_path")))],
        "produces": ["report", "artifacts"],
    },
}


