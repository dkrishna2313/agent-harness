def _load_profiles(ctx: AgentContext) -> list[Any]:
    from research_agent.profile import load_profile
    profiles: list[Any] = []
    for name in ctx.profiles:
        try:
            profiles.append(load_profile(name))
        except Exception:
            pass
    return profiles


def _build_retriever(knowledge_store: Path | None):
    """Best-effort Knowledge Layer retriever (lexical works without an API key)."""
    if not knowledge_store or not knowledge_store.exists():
        return None
    try:
        from knowledge.store import KnowledgeStore
        from knowledge.retriever import EvidenceRetriever
        from knowledge.embeddings import get_provider
        from knowledge.health import check_store_health
        ks = KnowledgeStore(knowledge_store)
        if not check_store_health(ks).runtime_ready:
            LOGGER.warning("[harness] knowledge store not runtime-ready — legacy retrieval")
            return None
        try:
            provider = get_provider()
        except Exception:
            provider = None
        return EvidenceRetriever(ks, provider=provider)
    except Exception as exc:
        LOGGER.warning("[harness] retriever init failed (%s) — legacy retrieval", exc)
        return None


def _check_conditions(conditions: list[tuple[str, Callable]], ctx: AgentContext, kind: str) -> list[str]:
    failures = []
    for desc, pred in conditions:
        try:
            ok = bool(pred(ctx))
        except Exception as exc:
            ok = False
            desc = f"{desc} (raised {type(exc).__name__})"
        if not ok:
            failures.append(desc)
    if failures:
        joined = "; ".join(failures)
        raise HarnessError(f"{kind} failed for agent: {joined}")
    return [desc for desc, _ in conditions]


def run_agent(
    agent_name: str,
    fixture_path: str | Path,
    *,
    no_llm: bool = False,
    model: str | None = None,
    sources: str | Path = "fixtures/sources",
    knowledge_store: str | Path | None = None,
    out_path: str | Path = "outputs/harness_report.md",
) -> dict[str, Any]:
    """Execute one agent in isolation; return {context, diff, mini_trace}."""
    if agent_name not in AGENT_REGISTRY:
        raise HarnessError(
            f"Unknown agent '{agent_name}'. Known: {', '.join(sorted(AGENT_REGISTRY))}"
        )
    spec = AGENT_REGISTRY[agent_name]

    ctx = load_context(fixture_path)
    before = context_to_jsonable(ctx)

    # Client (mock when --no-llm or no API key).
    from .cli import _build_client
    import os
    use_mock = no_llm or not os.getenv("ANTHROPIC_API_KEY")
    client = _build_client(mock=use_mock, model=model)
    ctx.trace["_client"] = client
    llm_before = len(getattr(client, "call_traces", []))

    profiles = _load_profiles(ctx)

    # Knowledge store auto-detect (mirrors functional CLI).
    ks_path = Path(knowledge_store) if knowledge_store else None
    if ks_path is None and Path("knowledge_store").exists():
        ks_path = Path("knowledge_store")
    cfg = {
        "sources": Path(sources),
        "out": Path(out_path),
        "retriever": _build_retriever(ks_path) if agent_name == "evidence" else None,
        "rerank": False,
    }

    # Build the agent.
    mod_name, cls_name = spec["import"]
    module = __import__(f"functional_agents.{mod_name}", fromlist=[cls_name])
    agent_cls = getattr(module, cls_name)
    agent = spec["build"](agent_cls, client, profiles, cfg)

    # Optional per-agent preparation (e.g. rebuild non-JSON scratch objects).
    if spec.get("prepare"):
        spec["prepare"](ctx)

    # Preconditions (pre-run harness usage failures raise HarnessError).
    pre_checked = _check_conditions(spec["pre"], ctx, "Precondition")

    # Execute. Execution-time failures (e.g. LLM boundary rejection) are captured
    # into the mini trace as a distinct error rather than crashing the harness,
    # so boundary stages/failures are always reported.
    status = "error"
    post_checked: list[str] = []
    exec_error: str | None = None
    t0 = time.monotonic()
    try:
        result = agent.run(ctx)
        ctx = result.context
        status = result.status
        post_checked = _check_conditions(spec["post"], ctx, "Postcondition")
    except HarnessError as exc:      # postcondition failure
        exec_error = str(exc)
    except Exception as exc:          # agent / boundary execution failure
        exec_error = f"{type(exc).__name__}: {exc}"
    elapsed_ms = round((time.monotonic() - t0) * 1000, 1)

    after = context_to_jsonable(ctx)
    diff = context_diff(before, after)

    llm_calls = len(getattr(client, "call_traces", [])) - llm_before
    norm = ctx.trace.get("_llm_normalization")
    # PH2.1 — surface any LLM-boundary diagnostics (keys ending in _boundary).
    boundary = {
        k: v for k, v in ctx.trace.items()
        if isinstance(k, str) and k.endswith("_boundary")
    }
    # PH3.3 — surface any applied prompt-slice diagnostics (keys ending in
    # _prompt_slice), additively — absent entirely for agents PH3.3 didn't touch.
    prompt_slice = {
        k: v for k, v in ctx.trace.items()
        if isinstance(k, str) and k.endswith("_prompt_slice")
    }
    warnings = [
        h.get("summary", "") for h in ctx.agent_history
        if h.get("status") in ("warning", "error")
    ]

    mini_trace = {
        "agent": agent_name,
        "agent_class": cls_name,
        "status": status,
        "error": exec_error,
        "execution_time_ms": elapsed_ms,
        "llm_call_count": llm_calls,
        "llm_mode": "mock" if use_mock else "live",
        "normalization": norm,
        "boundary": boundary,
        "prompt_slice": prompt_slice,
        "validation": {
            "preconditions_passed": pre_checked,
            "postconditions_passed": post_checked,
        },
        "objects_produced": diff["added"] + diff["modified"],
        "warnings": warnings,
    }

    return {"context": after, "diff": diff, "mini_trace": mini_trace}


